"""Step 1: トリアージエージェントのプロンプト定義

ユーザーからの問い合わせ文を受け取り、問い合わせの「カテゴリ分類」および「緊急度」を判定します。
また、問い合わせ文から顧客名や会社名などの特定情報を抽出します。
"""

from typing import Literal
from pydantic import BaseModel, Field


class TriageResult(BaseModel):
    """トリアージエージェントの構造化出力スキーマ。

    問い合わせのカテゴリ分類、緊急度、顧客識別情報、要約、推奨方針を定義します。
    """

    category: Literal[
        "技術的課題",
        "不具合報告",
        "契約/請求",
        "機能要望",
        "その他",
    ] = Field(
        ...,
        description="問い合わせのカテゴリ分類（技術的課題、不具合報告、契約/請求、機能要望、その他）",
    )
    urgency: Literal["高", "中", "低"] = Field(
        ...,
        description="問い合わせの緊急度（高: 重大障害/解約危機、中: 一部機能不具合/期限あり、低: 操作質問/一般要望）",
    )
    customer_identifier: str = Field(
        default="不明",
        description="問い合わせ文中に含まれる会社名、顧客名、ユーザーIDなどの顧客識別情報（不明な場合は「不明」）",
    )
    summary: str = Field(
        ...,
        description="顧客の主訴（何に困っているか、何を求めているか）に関する2〜3行の簡潔な要約",
    )
    recommended_action: str = Field(
        ...,
        description="後続エージェントで調査すべきポイントや推奨対応方針",
    )


